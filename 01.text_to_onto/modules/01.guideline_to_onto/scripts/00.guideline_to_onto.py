import argparse
import json
import os
import sys
import time
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
MODULE_ROOT = SCRIPT_DIR.parent

# Reuse this module's helpers and the sibling model wrappers
# without requiring the command to be launched from a specific working directory.
if str(SCRIPT_DIR) not in sys.path:
    sys.path.append(str(SCRIPT_DIR))

from src.endpoint_filters import (
    EndpointOntologyFilterBuilder,
    load_endpoint_rows,
    write_json,
)
from src.ontology import OntologyTree

DEFAULT_HF_HOME = "/nfs/research/ewald/ricos/huggingface_cache"
DEFAULT_HF_TRANSFER = "1"
DEFAULT_ENDPOINTS = (
    MODULE_ROOT
    / "outputs"
    / "endpoints"
    / "normalized_endpoint_list.csv"
)


def arg_parser():
    """Define CLI arguments for endpoint-to-ontology filter generation."""

    parser = argparse.ArgumentParser(
        description="Build endpoint-derived ontology subtree filters."
    )
    parser.add_argument(
        "--input_endpoints",
        default=str(DEFAULT_ENDPOINTS),
        help="Path to normalized_endpoint_list.csv from prepare_guidelines.",
    )
    parser.add_argument(
        "--output_dir",
        default=str(MODULE_ROOT / "outputs"),
        help="Directory where ontology-specific filter outputs are written.",
    )
    parser.add_argument(
        "--ontology",
        required=True,
        choices=["mp", "hpath", "aop", "hp", "txpo"],
        help="Ontology key to process.",
    )
    parser.add_argument(
        "--ontology_embedding_db",
        required=True,
        help="Path to ontology SQLite DB generated by prepare_ontologies.",
    )
    parser.add_argument(
        "--global_definitions_db",
        default=None,
        help="Optional SQLite DB with URI-level LLM-generated definitions.",
    )
    parser.add_argument(
        "--model_config",
        default=str(MODULE_ROOT / "config" / "models" / "Qwen3.5-122B-A10B-FP8.json"),
        help="Path to OpenAI-compatible chat model config JSON.",
    )
    parser.add_argument(
        "--base_url",
        default=None,
        help="Base URL for the LLM API. Overrides model_config if provided.",
    )
    parser.add_argument(
        "--system_prompt_file",
        default=str(MODULE_ROOT / "config" / "system_prompt_endpoint_filter.txt"),
        help="Endpoint discoverability system prompt.",
    )
    parser.add_argument(
        "--context_ontology",
        default="",
        help="Ontology context string or path to a context text file.",
    )

    parser.add_argument(
        "--max_depth",
        type=int,
        default=12,
        help="Maximum ontology traversal depth per endpoint.",
    )
    parser.add_argument(
        "--max_concurrency",
        type=int,
        default=None,
        help="Maximum concurrent LLM calls. Defaults to model_config max_concurrency.",
    )
    parser.add_argument(
        "--rag_config",
        required=True,
        help="Path to RAG configuration JSON file.",
    )
    parser.add_argument(
        "--embeddings_model_id",
        default=None,
        help="Identifier for the model configuration in RAG config (e.g., qwen, nemotron)",
    )
    parser.add_argument(
        "--mode",
        type=int,
        default=1,
        choices=[1, 2],
        help="Execution mode: 1 for individual verification, 2 for batch selection."
    )
    parser.add_argument(
        "--consensus_runs",
        type=int,
        default=3,
        help="Number of runs for majority voting consensus."
    )
    parser.add_argument(
        "--root_name",
        default=None,
        help="Optional exact ontology term name to use as the traversal root.",
    )
    parser.add_argument(
        "--debug_limit",
        type=int,
        default=None,
        help="Process only the first N endpoint rows.",
    )
    parser.add_argument("--hf_home", default=None, help="HuggingFace cache directory.")
    parser.add_argument("--hf_transfer", default=None, help="Enable/disable HF transfer.")


    return parser.parse_args()


def load_text_or_file(value: str) -> str:
    """Accept either literal context text or a path to a context text file."""

    if not value:
        return ""
    try:
        path = Path(value)
        if path.exists() and path.is_file():
            return path.read_text(encoding="utf-8").strip()
    except OSError:
        pass
    return value


def main():
    """Run the endpoint-to-phenotype filter pipeline."""

    start_time = time.time()
    args = arg_parser()

    # The LLM wrapper is imported after sys.path setup so this new module can
    # share the existing text_to_onto model implementation.
    from model.llm import get_model, test_model

    # Keep the same HuggingFace/cache defaults used by the rest of the project,
    # while still allowing environment variables or CLI arguments to override them.
    hf_home = args.hf_home or os.environ.get("HF_HOME") or DEFAULT_HF_HOME
    hf_transfer = args.hf_transfer or os.environ.get("HF_HUB_ENABLE_HF_TRANSFER") or DEFAULT_HF_TRANSFER
    os.environ["HF_HOME"] = hf_home
    os.environ["HF_HUB_ENABLE_HF_TRANSFER"] = hf_transfer

    input_endpoints = Path(args.input_endpoints)
    # Mapping files (txt and json) go into a subfolder per ontology
    output_dir = Path(args.output_dir) / "guidelines_mapping" / args.ontology

    if not input_endpoints.exists():
        raise FileNotFoundError(f"Endpoint input not found: {input_endpoints}")

    # Model config follows the existing repository convention. max_concurrency is
    # consumed here because it controls batching, not model construction.
    with open(args.model_config, "r", encoding="utf-8") as handle:
        model_config = json.load(handle)

    config_concurrency = model_config.pop("max_concurrency", 10)
    max_concurrency = args.max_concurrency or config_concurrency
    if args.base_url:
        model_config["base_url"] = args.base_url

    with open(args.rag_config, 'r', encoding='utf-8') as f:
        rag_config = json.load(f)

    # If it's a nested dictionary (e.g. keyed by model name), look up by embeddings_model_id
    if isinstance(rag_config, dict) and "embedding_model" not in rag_config:
        key = args.embeddings_model_id
        if key:
            # Case-insensitive key lookup
            rag_config_lower = {k.lower(): v for k, v in rag_config.items()}
            model_config_block = rag_config_lower.get(key.lower())
            if not model_config_block:
                # Fallback scan for embedding_model match if key was not found
                model_config_block = next((v for v in rag_config.values() if isinstance(v, dict) and v.get("embedding_model") == key), None)

            if model_config_block:
                rag_config = model_config_block

    embedding_model = rag_config.get("embedding_model", "Qwen/Qwen3-Embedding-8B")
    top_k_rag = rag_config.get("top_k_rag", 15)
    threshold_rag = rag_config.get("threshold_rag", 0.5)
    reranker_model = rag_config.get("reranker_model", "Qwen/Qwen3-Reranker-8B")
    threshold_reranker = rag_config.get("threshold_reranker", 0.0)
    reranker_batch_size = rag_config.get("reranker_batch_size", 32)
    reranker_prompt_file = rag_config.get("reranker_prompt")

    print("=== Endpoints To Phenotypes ===")
    print(f"Ontology: {args.ontology}")
    print(f"Input endpoints: {input_endpoints}")
    print(f"Ontology DB: {args.ontology_embedding_db}")
    print(f"Output directory: {output_dir}")
    print(f"Max concurrency: {max_concurrency}")

    llm = get_model(**model_config)
    test_retries = model_config.get("max_retries", 3)
    if not test_model(llm, max_retries=test_retries):
        raise RuntimeError("Model connectivity test failed.")

    # Inputs come from previous repository stages: normalized OECD endpoints and
    # processed ontology SQLite DBs.
    endpoints = load_endpoint_rows(input_endpoints, debug_limit=args.debug_limit)
    if not endpoints:
        raise ValueError(f"No endpoint rows found in {input_endpoints}")

    tree = OntologyTree.from_db(args.ontology_embedding_db, args.global_definitions_db)
    system_prompt = Path(args.system_prompt_file).read_text(encoding="utf-8")
    context_ontology = load_text_or_file(args.context_ontology)

    # The builder performs the LLM-guided ontology traversal and returns all
    # artifacts as in-memory rows before they are written below.
    builder = EndpointOntologyFilterBuilder(
        ontology=args.ontology,
        tree=tree,
        system_prompt=system_prompt,
        context_ontology=context_ontology,
        max_depth=args.max_depth,
        max_concurrency=max_concurrency,
        root_name=args.root_name,
        embedding_model_name=embedding_model,
        top_k_rag=top_k_rag,
        threshold_rag=threshold_rag,
        reranker_model=reranker_model,
        threshold_reranker=threshold_reranker,
        reranker_batch_size=reranker_batch_size,
        reranker_prompt_file=reranker_prompt_file,
        mode=args.mode,
        consensus_runs=args.consensus_runs,
        max_retries=test_retries,
    )

    endpoint_rows, guideline_rows, unique_rows, reasoning = builder.build_for_endpoints(llm, endpoints)

    # 1. Create a directory for per-guideline CSV files
    guideline_dir = output_dir / "guidelines"
    guideline_dir.mkdir(parents=True, exist_ok=True)

    # 2. Group guideline_rows by guideline number and write separate files
    from collections import defaultdict
    by_guideline = defaultdict(list)
    for row in guideline_rows:
        g_num = row.get("guideline_number", "unknown")
        by_guideline[g_num].append(row)

    for g_num, rows in by_guideline.items():
        # Clean the filename
        safe_g_num = "".join(c for c in str(g_num) if c.isalnum() or c in "._-")
        output_txt = guideline_dir / f"{safe_g_num}.txt"

        # Write unique term breadcrumbs (full tree path), one per line
        unique_paths = sorted({row["breadcrumb"] for row in rows})
        with open(output_txt, "w", encoding="utf-8") as f:
            for path in unique_paths:
                f.write(f"{path}\n")

    # 3. Write the JSON reasoning trace
    reasoning_path = write_json(
        output_dir / "endpoint_ontology_reasoning.json",
        reasoning,
    )

    elapsed = time.time() - start_time
    print(f"Wrote {len(by_guideline)} guideline-specific CSV files to {guideline_dir}")
    print(f"Wrote reasoning trace: {reasoning_path}")


    print(f"Completed in {elapsed:.2f}s")




if __name__ == "__main__":
    main()
