from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
MODULE_ROOT = SCRIPT_DIR.parent
TOXVALDB_ROOT = MODULE_ROOT.parents[2]
REPO_ROOT = TOXVALDB_ROOT.parent

